from __future__ import annotations

import os
from pathlib import Path
from typing import Any, Dict, Optional, List

import joblib
import numpy as np
import pandas as pd

from .feature_config import (
    MODEL_FEATURES,
    LABEL_ORDER,
    FEATURE_METADATA,
    NUMERIC_DEFAULTS,
    BINARY_FEATURES,
    STAGE1_FEATURES,
    STAGE2_FEATURES,
)

# Default to the deployed Final Model C full-development package produced by
# misc/notebooks/nhanes-model-c-train-save-download-and-predict.ipynb.
DEFAULT_MODEL_PATH = (
    Path(__file__).resolve().parents[1] / "model_package" / "FINAL_MODEL_C_FULL_DEVELOPMENT.joblib"
)

REFERENCE_VALUES: Dict[str, float] = {
    **{k: float(v) for k, v in NUMERIC_DEFAULTS.items()},
    **{k: 0.0 for k in BINARY_FEATURES},
}


class ModelNotLoadedError(RuntimeError):
    pass


class KidneyRiskModelService:
    """Serving wrapper around the Final Model C two-stage cascade package.

    The deployed package is a plain ``dict`` (no custom pickle classes required):

        {
            "stage1": {"features": [...13...], "preprocessor": ColumnTransformer, "model": RandomForest},
            "stage2": {"features": [...6...],  "preprocessor": ColumnTransformer, "model": GradientBoosting},
            "thresholds": {"stage1": 0.44, "stage2": 0.50},
            "unique_inputs": [...14...],
            ...metadata...
        }

    Scoring reproduces the notebook cascade exactly:
        p1 = P(at-risk)          from Stage-1
        p2 = P(high | at-risk)   from Stage-2
        class = low            if p1 <  stage1_threshold
                high            if p1 >= stage1_threshold and p2 >= stage2_threshold
                moderate        otherwise
        probabilities = [1-p1, p1*(1-p2), p1*p2]  (row-normalized)
    """

    def __init__(self, model_path: Optional[str | Path] = None):
        self.model_path = Path(model_path or os.getenv("CKD_MODEL_PATH", DEFAULT_MODEL_PATH))
        self.package: Optional[Dict[str, Any]] = None
        self.stage1: Optional[Dict[str, Any]] = None
        self.stage2: Optional[Dict[str, Any]] = None
        self.stage1_threshold: float = 0.44
        self.stage2_threshold: float = 0.50
        self.model_features = list(MODEL_FEATURES)
        self.label_order = list(LABEL_ORDER)
        self.loaded = False
        self.load_error: Optional[str] = None
        self.model_info: Dict[str, Any] = {}
        self.load()

    def load(self) -> None:
        try:
            if not self.model_path.exists():
                raise FileNotFoundError(
                    f"Model package not found at {self.model_path}. Copy the .joblib file generated by the "
                    "Final Model C notebook into model_package/ or set CKD_MODEL_PATH to the package path."
                )
            obj = joblib.load(self.model_path)
            if not (isinstance(obj, dict) and "stage1" in obj and "stage2" in obj):
                raise ValueError(
                    "Unrecognized model package format. Expected the Final Model C dict package with "
                    "'stage1', 'stage2', 'thresholds' and 'unique_inputs' keys."
                )

            self.package = obj
            self.stage1 = obj["stage1"]
            self.stage2 = obj["stage2"]

            thresholds = obj.get("thresholds") or {}
            self.stage1_threshold = float(thresholds.get("stage1", 0.44))
            self.stage2_threshold = float(thresholds.get("stage2", 0.50))

            self.model_features = list(
                obj.get("unique_inputs") or MODEL_FEATURES
            )
            self.label_order = list(obj.get("label_order") or LABEL_ORDER)

            self.model_info = {
                "model_name": obj.get("model_name", "Final Model C"),
                "model_status": obj.get("model_status", "Selected deployment model"),
                "package_version": obj.get("package_version"),
                "training_scope": obj.get("training_scope"),
                "training_n": obj.get("training_n"),
                "training_class_counts": obj.get("training_class_counts", {}),
                "seed": obj.get("seed"),
                "stage1_threshold": self.stage1_threshold,
                "stage2_threshold": self.stage2_threshold,
                "stage1_features": list(obj.get("stage1_features") or STAGE1_FEATURES),
                "stage2_features": list(obj.get("stage2_features") or STAGE2_FEATURES),
                "unique_inputs": list(self.model_features),
                "versions": obj.get("versions", {}),
                "scientific_boundary": obj.get(
                    "scientific_boundary",
                    "Kidney-risk screening proxy; not a confirmed CKD diagnosis.",
                ),
                "explanation_method": "model-agnostic local perturbation against reference input values",
            }
            self.loaded = True
            self.load_error = None
        except Exception as exc:
            self.loaded = False
            self.load_error = str(exc)
            self.package = None
            self.stage1 = None
            self.stage2 = None

    def assert_loaded(self) -> None:
        if not self.loaded or self.package is None:
            raise ModelNotLoadedError(self.load_error or "Model is not loaded.")

    def _clean_payload(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        row = {feature: payload.get(feature, None) for feature in self.model_features}

        # Live-input consistency rule: if the patient reports no hypertension and
        # leaves BP-medicine blank, treat it as not taking BP medicine (matches the
        # structural-missing handling used when the model was trained).
        if row.get("hypertension_doctor_told") == 0 and row.get("taking_bp_medicine") is None:
            row["taking_bp_medicine"] = 0

        for k, v in list(row.items()):
            if v == "" or v == "None":
                row[k] = None
        return row

    def make_dataframe(self, payload: Dict[str, Any]) -> pd.DataFrame:
        row = self._clean_payload(payload)
        row = {k: (np.nan if v is None else v) for k, v in row.items()}
        return pd.DataFrame([row], columns=self.model_features)

    @staticmethod
    def _positive_proba(component: Dict[str, Any], frame: pd.DataFrame) -> np.ndarray:
        """P(positive class = 1) for a stage, through its stored preprocessor + model."""
        transformed = component["preprocessor"].transform(frame[component["features"]])
        model = component["model"]
        classes = list(model.classes_)
        if 1 not in classes:
            return np.zeros(len(frame), dtype=float)
        return model.predict_proba(transformed)[:, classes.index(1)]

    def _score_df(self, X: pd.DataFrame) -> Dict[str, Any]:
        """Two-stage cascade scoring for a single-row DataFrame."""
        p_atrisk = float(self._positive_proba(self.stage1, X)[0])
        p_high_cond = float(self._positive_proba(self.stage2, X)[0])

        gate = p_atrisk >= self.stage1_threshold
        if not gate:
            risk_class = "low"
        elif p_high_cond >= self.stage2_threshold:
            risk_class = "high"
        else:
            risk_class = "moderate"

        p_low = 1.0 - p_atrisk
        p_moderate = p_atrisk * (1.0 - p_high_cond)
        p_high = p_atrisk * p_high_cond
        total = p_low + p_moderate + p_high
        if total > 0:
            p_low, p_moderate, p_high = p_low / total, p_moderate / total, p_high / total

        probabilities = {"low": p_low, "moderate": p_moderate, "high": p_high}
        confidence = float(max(probabilities.values()))
        return {
            "risk_class": risk_class,
            "probabilities": probabilities,
            "confidence": confidence,
            "stage1": {
                "p_atrisk": p_atrisk,
                "threshold": self.stage1_threshold,
                "sent_to_stage2": bool(gate),
            },
            "stage2": {
                "p_high_given_atrisk": p_high_cond,
                "threshold": self.stage2_threshold,
                "applied_to_final_decision": bool(gate),
            },
        }

    def _local_explanation(self, X: pd.DataFrame, base_score: Dict[str, Any], max_features: int = 8) -> Dict[str, Any]:
        """Model-agnostic local explanation.

        For each supplied feature, replace the current value with a fixed reference value and observe how much
        the final predicted-class probability changes. Positive contribution means the current value supports
        the final model output compared with that reference. This is not SHAP and not causal.
        """
        risk_class = base_score["risk_class"]
        base_probs = base_score["probabilities"]
        base_target_prob = float(base_probs.get(risk_class, 0.0))
        row = X.iloc[0].copy()
        impacts: List[Dict[str, Any]] = []

        for feature in self.model_features:
            current_value = row.get(feature, np.nan)
            if pd.isna(current_value):
                continue
            if feature not in REFERENCE_VALUES:
                continue
            reference_value = REFERENCE_VALUES[feature]
            try:
                if float(current_value) == float(reference_value):
                    continue
            except Exception:
                pass

            X_ref = X.copy()
            X_ref.loc[X_ref.index[0], feature] = reference_value
            alt_score = self._score_df(X_ref)
            alt_prob = float(alt_score["probabilities"].get(risk_class, 0.0))
            contribution = base_target_prob - alt_prob
            meta = FEATURE_METADATA.get(feature, {})
            impacts.append({
                "feature": feature,
                "label": meta.get("label", feature),
                "unit": meta.get("unit", ""),
                "current_value": None if pd.isna(current_value) else float(current_value),
                "reference_value": float(reference_value),
                "contribution_to_predicted_class": float(contribution),
                "absolute_contribution": float(abs(contribution)),
                "direction": "supports_prediction" if contribution >= 0 else "pulls_away_from_prediction",
            })

        impacts = sorted(impacts, key=lambda d: d["absolute_contribution"], reverse=True)[:max_features]
        return {
            "method": "local_perturbation",
            "description": (
                "Each listed feature was temporarily replaced by a reference value and the predicted-class probability was recalculated. "
                "Positive values support the final model output compared with that reference. This is model-behavior explanation, not a causal or clinical diagnosis."
            ),
            "predicted_class_probability": base_target_prob,
            "top_factors": impacts,
        }

    def _reliability(self, score: Dict[str, Any], n_missing: int) -> Dict[str, Any]:
        confidence = float(score.get("confidence", 0.0))
        probs = score.get("probabilities", {}) or {}
        ordered = sorted([float(v) for v in probs.values()], reverse=True)
        margin = ordered[0] - ordered[1] if len(ordered) >= 2 else ordered[0] if ordered else 0.0
        p_atrisk = float((score.get("stage1") or {}).get("p_atrisk", 0.0))
        t1 = float((score.get("stage1") or {}).get("threshold", self.stage1_threshold))
        near_boundary = abs(p_atrisk - t1) <= 0.06 or margin < 0.15
        if n_missing >= 5 or confidence < 0.50 or margin < 0.08:
            level = "low"
        elif near_boundary or confidence < 0.65 or n_missing >= 2:
            level = "moderate"
        else:
            level = "high"
        notes = []
        if near_boundary:
            notes.append("Prediction is near a model decision boundary.")
        if n_missing:
            notes.append(f"{n_missing} feature(s) were missing and handled by the trained preprocessing pipeline.")
        if margin < 0.15:
            notes.append("The gap between the top two class probabilities is relatively small.")
        if not notes:
            notes.append("Input completeness and probability margin are acceptable for a screening-support output.")
        return {
            "level": level,
            "confidence": confidence,
            "probability_margin": float(margin),
            "near_boundary": bool(near_boundary),
            "notes": notes,
        }

    def _build_llm_context(self, payload: Dict[str, Any], score: Dict[str, Any], explanation: Dict[str, Any], input_quality: Dict[str, Any], reliability: Dict[str, Any]) -> Dict[str, Any]:
        factors = explanation.get("top_factors", [])[:6]
        return {
            "purpose": "Generate non-clinical, supportive lifestyle guidance based on the model screening output.",
            "strict_safety_rules": [
                "Do not diagnose CKD or any disease.",
                "Do not prescribe medication, dosage, supplements, or treatment.",
                "Do not tell the user to stop or start any medicine.",
                "Do not replace clinician judgment, eGFR testing, or UACR testing.",
                "Advice should focus only on general wellness: balanced food habits, sleep routine, rest, hydration habits, physical activity, and when to seek professional review.",
            ],
            "model_output": {
                "screening_category": score["risk_class"],
                "class_probabilities": score["probabilities"],
                "confidence": score["confidence"],
                "reliability_level": reliability["level"],
                "reliability_notes": reliability["notes"],
            },
            "key_model_factors": factors,
            "input_quality": input_quality,
            "patient_inputs": payload,
            "suggestion_style": {
                "tone": "calm, supportive, simple, non-alarming",
                "sections": ["Food habits", "Rest and sleep", "Daily routine", "Follow-up reminder"],
                "avoid": ["diagnosis", "treatment claims", "medication instructions", "specific medical prescriptions"],
            },
        }

    def predict(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        self.assert_loaded()
        clean_payload = self._clean_payload(payload)
        X = self.make_dataframe(clean_payload)
        score = self._score_df(X)

        risk_class = score["risk_class"]
        missing_features = [c for c in self.model_features if pd.isna(X.iloc[0][c])]
        supplied_features = [c for c in self.model_features if c not in missing_features]
        input_quality = {
            "n_model_features": len(self.model_features),
            "n_supplied_features": len(supplied_features),
            "n_missing_features": len(missing_features),
            "missing_features": missing_features,
            "feature_labels": {f: FEATURE_METADATA.get(f, {}).get("label", f) for f in self.model_features},
        }
        explanation = self._local_explanation(X, score)
        reliability = self._reliability(score, len(missing_features))
        llm_context = self._build_llm_context(clean_payload, score, explanation, input_quality, reliability)

        return {
            "risk_class": risk_class,
            "risk_class_display": self._display_class(risk_class),
            "probabilities": score["probabilities"],
            "confidence": score["confidence"],
            "stage1": score["stage1"],
            "stage2": score["stage2"],
            "input_quality": input_quality,
            "reliability": reliability,
            "explanation": explanation,
            "llm_context": llm_context,
            "model_info": self.model_info,
            "clinical_note": (
                "This output is for kidney-risk screening support only. It is not a medical diagnosis and should not replace "
                "clinical assessment, eGFR/UACR testing, or clinician judgment."
            ),
        }

    @staticmethod
    def _display_class(label: str) -> str:
        return {
            "low": "Low kidney-risk screening category",
            "moderate": "Moderate kidney-risk screening category",
            "high": "High kidney-risk screening category",
        }.get(label, label)


service = KidneyRiskModelService()
