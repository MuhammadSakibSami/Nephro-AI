"""## Phase 1.5 — Three-Zone Stage-1 Gate

Two-zone (original):
  p_at_risk < 0.440 → LOW
  p_at_risk ≥ 0.440 → Stage-2 (moderate or high)

Three-zone (Experiment C from PDF, best config):
  p_at_risk < 0.440 → LOW (directly)
  0.440 ≤ p_at_risk < 0.540 → MODERATE (directly, skips Stage-2)
  p_at_risk ≥ 0.540 → Stage-2 (moderate or high)

Goal: check if three-zone reduces moderate-to-low errors at the cost of high recall.
Full error decomposition reported, including high→low vs high→moderate.
"""

print("\n" + "="*60)
print("PHASE 1.5 — Three-Zone Stage-1 Gate with Full Error Decomposition")
print("="*60)

T_LOW  = 0.440
T_HIGH = 0.540
S2_THR = STAGE2_THRESHOLD   # 0.500

# Get raw Stage-1 and Stage-2 probabilities from reference cascade
detail_ref = ref_cascade.predict_detail(X_test)
p_at_ref   = detail_ref["p_atrisk_stage1"].values
p_high_cond = detail_ref["p_high_given_atrisk_stage2"].values

# ─── Two-zone (original) ────────────────────────────────────────────────────
pred_2zone = np.where(p_at_ref < T_LOW, "low",
             np.where(p_high_cond >= S2_THR, "high", "moderate"))

# ─── Three-zone ─────────────────────────────────────────────────────────────
pred_3zone = np.where(
    p_at_ref < T_LOW, "low",
    np.where(
        p_at_ref < T_HIGH, "moderate",               # uncertain zone → directly moderate
        np.where(p_high_cond >= S2_THR, "high", "moderate")   # stage-2 decision
    )
)

y_test_np = np.asarray(y_test)

def full_error_decomposition(y_true, y_pred, label=""):
    cm = confusion_matrix(y_true, y_pred, labels=LABEL_ORDER)
    m, _ = evaluate_predictions(y_true, y_pred, None)
    low_i, mod_i, hgh_i = 0, 1, 2
    rows = []
    for ai, actual in enumerate(LABEL_ORDER):
        for pi, pred in enumerate(LABEL_ORDER):
            rows.append({
                "actual": actual, "predicted": pred, "count": int(cm[ai, pi]),
                "label": label,
            })
    # Per-class support
    n_high = cm[hgh_i].sum()
    n_mod  = cm[mod_i].sum()
    n_low  = cm[low_i].sum()
    summary = {
        "label": label,
        "accuracy": m["accuracy"],
        "balanced_accuracy": m["balanced_accuracy"],
        "macro_f1": m["macro_f1"],
        "low_recall":      m["low_recall"],
        "moderate_recall": m["moderate_recall"],
        "high_recall":     m["high_recall"],
        "high_to_low_miss_count":      int(cm[hgh_i, low_i]),
        "high_to_low_miss_rate":       safe_div(cm[hgh_i, low_i], n_high),
        "high_to_moderate_count":      int(cm[hgh_i, mod_i]),
        "high_to_moderate_rate":       safe_div(cm[hgh_i, mod_i], n_high),
        "moderate_to_low_count":       int(cm[mod_i, low_i]),
        "moderate_to_low_rate":        safe_div(cm[mod_i, low_i], n_mod),
        "moderate_to_high_count":      int(cm[mod_i, hgh_i]),
        "low_to_atrisk_count":         int(cm[low_i, mod_i] + cm[low_i, hgh_i]),
        "low_to_high_count":           int(cm[low_i, hgh_i]),
        "n_high_test": int(n_high),
        "n_moderate_test": int(n_mod),
        "n_low_test": int(n_low),
    }
    return summary, pd.DataFrame(rows), cm


summary_2z, cell_2z, cm_2z = full_error_decomposition(y_test_np, pred_2zone, "two_zone_original")
summary_3z, cell_3z, cm_3z = full_error_decomposition(y_test_np, pred_3zone, f"three_zone_t{T_LOW}_{T_HIGH}")

