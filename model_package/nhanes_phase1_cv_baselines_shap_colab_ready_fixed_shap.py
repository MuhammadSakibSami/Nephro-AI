def safe_div(num, den):
    return num / den if den else np.nan


def multiclass_brier(y_true, y_proba):
    y_true = pd.Series(y_true).astype(str).values
    y_bin = label_binarize(y_true, classes=LABEL_ORDER)
    return float(np.mean(np.sum((y_proba - y_bin) ** 2, axis=1)))


def safe_roc_auc(y_true, y_proba):
    y_true = pd.Series(y_true).astype(str).values
    y_bin = label_binarize(y_true, classes=LABEL_ORDER)
    try:
        macro = roc_auc_score(y_bin, y_proba, average="macro", multi_class="ovr")
    except Exception:
        macro = np.nan
    try:
        weighted = roc_auc_score(y_bin, y_proba, average="weighted", multi_class="ovr")
    except Exception:
        weighted = np.nan
    return macro, weighted


def evaluate_predictions(y_true, y_pred, y_proba=None):
    """Return (metrics_dict, confusion_matrix_array)."""
    y_true = pd.Series(y_true).astype(str).values
    y_pred = pd.Series(y_pred).astype(str).values
    cm = confusion_matrix(y_true, y_pred, labels=LABEL_ORDER)
    precision, recall, f1, support = precision_recall_fscore_support(
        y_true, y_pred, labels=LABEL_ORDER, zero_division=0
    )
    m = {
        "accuracy":          accuracy_score(y_true, y_pred),
        "balanced_accuracy": balanced_accuracy_score(y_true, y_pred),
        "macro_f1":          f1_score(y_true, y_pred, labels=LABEL_ORDER, average="macro",     zero_division=0),
        "weighted_f1":       f1_score(y_true, y_pred, labels=LABEL_ORDER, average="weighted",  zero_division=0),
        "macro_precision":   precision_score(y_true, y_pred, labels=LABEL_ORDER, average="macro",    zero_division=0),
        "macro_recall":      recall_score(y_true, y_pred, labels=LABEL_ORDER, average="macro",   zero_division=0),
        "mcc":               matthews_corrcoef(y_true, y_pred),
        "cohen_kappa":       cohen_kappa_score(y_true, y_pred, labels=LABEL_ORDER),
    }
    for lbl, p, r, f, s in zip(LABEL_ORDER, precision, recall, f1, support):
        m[f"{lbl}_precision"] = p
        m[f"{lbl}_recall"]    = r
        m[f"{lbl}_f1"]        = f
        m[f"{lbl}_support"]   = int(s)

    low_i, mod_i, hgh_i = 0, 1, 2
    m["high_to_low_miss_count"]    = int(cm[hgh_i, low_i])
    m["high_to_low_miss_rate"]     = safe_div(cm[hgh_i, low_i], cm[hgh_i].sum())
    m["high_to_moderate_count"]    = int(cm[hgh_i, mod_i])
    m["high_to_moderate_rate"]     = safe_div(cm[hgh_i, mod_i], cm[hgh_i].sum())
    m["moderate_to_low_count"]     = int(cm[mod_i, low_i])
    m["moderate_to_low_rate"]      = safe_div(cm[mod_i, low_i], cm[mod_i].sum())
    m["moderate_to_high_count"]    = int(cm[mod_i, hgh_i])
    m["moderate_to_high_rate"]     = safe_div(cm[mod_i, hgh_i], cm[mod_i].sum())
    m["low_to_atrisk_count"]       = int(cm[low_i, mod_i] + cm[low_i, hgh_i])
    m["low_to_atrisk_rate"]        = safe_div(cm[low_i, mod_i] + cm[low_i, hgh_i], cm[low_i].sum())

    m["balanced_utility"] = (
        0.20 * m["macro_f1"] + 0.20 * m["balanced_accuracy"] +
        0.20 * m["high_recall"] + 0.20 * m["moderate_recall"] +
        0.10 * m["low_recall"] - 0.10 * m["high_to_low_miss_rate"]
    )

    if y_proba is not None:
        y_proba = np.asarray(y_proba, dtype=float)
        m["roc_auc_ovr_macro"], m["roc_auc_ovr_weighted"] = safe_roc_auc(y_true, y_proba)
        try:
            m["log_loss"] = log_loss(y_true, y_proba, labels=LABEL_ORDER)
        except Exception:
            m["log_loss"] = np.nan
        try:
            m["brier_multiclass"] = multiclass_brier(y_true, y_proba)
        except Exception:
            m["brier_multiclass"] = np.nan

    return m, cm


