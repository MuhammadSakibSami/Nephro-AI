def tune_s2_threshold(fitted_s1, fitted_s2, X_val, y_val,
                      s1_thr=STAGE1_THRESHOLD,
                      grid=CV_THR_GRID,
                      high_recall_min=CV_HIGH_RECALL_MIN,
                      h2l_max=CV_HIGH_TO_LOW_MAX):
    """Select Stage-2 threshold maximising moderate recall subject to safety constraints."""
    best_thr = 0.50
    best_mod_rec = -1.0
    y_val_arr = np.asarray(y_val)

    for thr in grid:
        cascade = assemble_cascade(fitted_s1, fitted_s2, s1_thr, float(thr), "tune_tmp")
        y_pred = cascade.predict(X_val)
        cm_v = confusion_matrix(y_val_arr, y_pred, labels=LABEL_ORDER)
        high_i, mod_i, low_i = 2, 1, 0
        high_support = cm_v[high_i].sum()
        high_rec = safe_div(cm_v[high_i, high_i], high_support) if high_support else 0.0
        mod_support  = cm_v[mod_i].sum()
        mod_rec  = safe_div(cm_v[mod_i, mod_i], mod_support) if mod_support else 0.0
        h2l = int(cm_v[high_i, low_i])

        if high_rec >= high_recall_min and h2l <= h2l_max and mod_rec > best_mod_rec:
            best_mod_rec = mod_rec
            best_thr = float(thr)

    return best_thr, best_mod_rec


