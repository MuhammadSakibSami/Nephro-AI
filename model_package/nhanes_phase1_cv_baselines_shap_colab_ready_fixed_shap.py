def extract_binary_shap_values_and_base(explainer, shap_values_raw, positive_index=1):
    """Return 2D SHAP values + scalar base value for binary tree models.

    SHAP/sklearn combinations can return:
      - list[class0, class1]
      - 2D array: (n_samples, n_features)
      - 3D array: (n_samples, n_features, n_classes)

    Some sklearn binary models, especially GradientBoostingClassifier,
    expose only one expected value for the positive-class margin. This helper
    safely uses class-1 when it exists, otherwise falls back to index 0.
    """
    if isinstance(shap_values_raw, list):
        idx = positive_index if len(shap_values_raw) > positive_index else 0
        vals = np.asarray(shap_values_raw[idx])
    else:
        arr = np.asarray(shap_values_raw)
        if arr.ndim == 3:
            idx = positive_index if arr.shape[2] > positive_index else 0
            vals = arr[:, :, idx]
        else:
            vals = arr

    ev = np.asarray(explainer.expected_value)
    if ev.ndim == 0:
        base = float(ev)
    else:
        flat = ev.ravel()
        idx = positive_index if len(flat) > positive_index else 0
        base = float(flat[idx])

    return vals, base

