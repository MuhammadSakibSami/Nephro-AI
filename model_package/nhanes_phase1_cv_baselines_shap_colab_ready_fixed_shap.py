def get_preprocessor_feature_names(preprocessor):
    try:
        return [x.replace("num__", "").replace("bin__", "") for x in preprocessor.get_feature_names_out()]
    except Exception:
        return []


def _to_dense(X):
    return X.toarray() if hasattr(X, "toarray") else np.asarray(X)


def aggregate_to_raw(transformed_names, scores, raw_features):
    rows = [{"raw": _n.replace("num__", "").replace("bin__", ""), "score": float(s)}
            for _n, s in zip(transformed_names, scores)]
    df_imp = pd.DataFrame(rows)
    if df_imp.empty:
        return pd.DataFrame({"feature": raw_features, "score": 0.0, "rank": range(1, len(raw_features)+1)})
    out = df_imp.groupby("raw", as_index=False)["score"].sum().rename(columns={"raw": "feature"})
    out = out[out["feature"].isin(raw_features)].copy()
    missing = [f for f in raw_features if f not in set(out["feature"])]
    if missing:
        out = pd.concat([out, pd.DataFrame({"feature": missing, "score": 0.0})], ignore_index=True)
    out = out.sort_values("score", ascending=False).reset_index(drop=True)
    out["rank"] = np.arange(1, len(out)+1)
    return out


def rank_features_rf_balanced(stage, feature_pool, X_train, y_train, seed=MAIN_RANDOM_STATE):
    """Rank features using rf_balanced on training data only — prevents leakage."""
    feature_pool = list(feature_pool)
    y_s = pd.Series(y_train).astype(str).reset_index(drop=True)
    if stage == "stage1":
        X_stage = X_train[feature_pool].reset_index(drop=True)
        y_stage = (y_s != "low").astype(int).values
    elif stage == "stage2":
        mask = (y_s != "low").values
        X_stage = X_train.loc[mask, feature_pool].reset_index(drop=True)
        y_stage = (y_s.loc[mask] == "high").astype(int).values
    else:
        raise ValueError(f"Unknown stage: {stage}")

    pre = make_preprocessor(feature_pool, X_stage)
    Xp = _to_dense(pre.fit_transform(X_stage[feature_pool]))
    names = get_preprocessor_feature_names(pre)

    rf = RandomForestClassifier(
        n_estimators=250, max_depth=7, min_samples_leaf=3,
        class_weight="balanced", random_state=seed, n_jobs=N_JOBS,
    )
    rf.fit(Xp, y_stage)
    return aggregate_to_raw(names, rf.feature_importances_, feature_pool)


def make_stage1_pipeline(stage1_features, X_reference, random_state=MAIN_RANDOM_STATE):
    return ImbPipeline([
        ("preprocess", make_preprocessor(stage1_features, X_reference)),
        ("sampler", RandomOverSampler(random_state=random_state)),
        ("model", RandomForestClassifier(
            n_estimators=STAGE1_RF_N_ESTIMATORS, max_depth=5, min_samples_leaf=2,
            max_features="sqrt", random_state=random_state, n_jobs=N_JOBS,
        )),
    ])


def make_stage2_pipeline(stage2_input_features, X_reference, random_state=MAIN_RANDOM_STATE):
    return ImbPipeline([
        ("preprocess", make_preprocessor(stage2_input_features, X_reference)),
        ("sampler", OBUResampler(
            k_neighbors=OBU_K_NEIGHBORS,
            majority_remove_frac=OBU_MAJORITY_REMOVE_FRAC,
            target_ratio=OBU_TARGET_RATIO,
            random_state=random_state,
        )),
        ("selector", TreeMedianSelector(
            random_state=random_state, n_estimators=SELECTOR_N_ESTIMATORS,
        )),
        ("model", GradientBoostingClassifier(
            n_estimators=STAGE2_GB_N_ESTIMATORS,
            learning_rate=0.05, max_depth=2, random_state=random_state,
        )),
    ])


def fit_stage1(stage1_features, X_train, y_train, random_state=MAIN_RANDOM_STATE):
    """Fit Stage-1 RF+ROS binary gate (low=0, at-risk=1)."""
    pipe = make_stage1_pipeline(stage1_features, X_train, random_state)
    y_bin = (pd.Series(y_train).astype(str) != "low").astype(int).values
    pipe.fit(X_train, y_bin)
    return pipe


def fit_stage2(stage2_input_features, X_train, y_train, random_state=MAIN_RANDOM_STATE):
    """Fit Stage-2 OBU+TreeMedian+GBM on at-risk subset (moderate=0, high=1)."""
    pipe = make_stage2_pipeline(stage2_input_features, X_train, random_state)
    y_s = pd.Series(y_train).astype(str).reset_index(drop=True)
    mask = (y_s != "low").values
    X_s2 = X_train.iloc[mask]
    y_s2 = (y_s.loc[mask] == "high").astype(int).values
    pipe.fit(X_s2, y_s2)
    return pipe


def assemble_cascade(fitted_s1, fitted_s2, s1_thr, s2_thr, name="cascade"):
    """Wrap pre-fitted Stage-1 and Stage-2 into a TwoStageCascade for evaluation."""
    model = TwoStageCascade(
        fitted_s1, fitted_s2,
        stage1_threshold=float(s1_thr),
        stage2_threshold=float(s2_thr),
        label_order=LABEL_ORDER,
        name=name,
    )
    model.classes_ = np.array(LABEL_ORDER)
    model.stage1_pipeline_ = fitted_s1
    model.stage2_pipeline_ = fitted_s2
    return model


def get_stage2_selected_features(stage2_pipeline, s2_input_features):
    pre = stage2_pipeline.named_steps["preprocess"]
    sel = stage2_pipeline.named_steps["selector"]
    names = get_preprocessor_feature_names(pre)
    mask = sel.get_support()
    raw_sel = []
    for n, keep in zip(names, mask):
        raw = n.replace("num__", "").replace("bin__", "")
        if keep and raw not in raw_sel:
            raw_sel.append(raw)
    return raw_sel


