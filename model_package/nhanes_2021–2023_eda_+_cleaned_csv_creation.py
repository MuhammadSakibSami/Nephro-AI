"""# GFR category, albuminuria category, and 3-class target"""

def gfr_category(egfr):
    if pd.isna(egfr):
        return np.nan
    if egfr >= 90:
        return "G1"
    elif egfr >= 60:
        return "G2"
    elif egfr >= 45:
        return "G3a"
    elif egfr >= 30:
        return "G3b"
    elif egfr >= 15:
        return "G4"
    else:
        return "G5"


def albuminuria_category(uacr):
    if pd.isna(uacr):
        return np.nan
    if uacr < 30:
        return "A1"
    elif uacr <= 300:
        return "A2"
    else:
        return "A3"


def kidney_risk_3class(g, a):
    if pd.isna(g) or pd.isna(a):
        return np.nan

    # Low risk
    if (g in ["G1", "G2"]) and (a == "A1"):
        return "Low"

    # Moderate risk
    if ((g in ["G1", "G2"]) and (a == "A2")) or ((g == "G3a") and (a == "A1")):
        return "Moderate"

    # High risk: high + very high collapsed
    return "High"


df["gfr_cat"] = df["egfr"].apply(gfr_category)
