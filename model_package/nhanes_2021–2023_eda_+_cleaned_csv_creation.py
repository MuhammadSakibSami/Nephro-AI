def set_outside_range_to_nan(dataframe, col, lower=None, upper=None):
    if col not in dataframe.columns:
        return dataframe

    before_missing = dataframe[col].isna().sum()

    if lower is not None:
        dataframe.loc[dataframe[col] < lower, col] = np.nan

    if upper is not None:
        dataframe.loc[dataframe[col] > upper, col] = np.nan

    after_missing = dataframe[col].isna().sum()
    print(f"{col}: added NaN = {after_missing - before_missing}")
    return dataframe


