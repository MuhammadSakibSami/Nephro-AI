"""# Pairwise feature overlap"""

def overlap_coefficient(x1, x2, bins=30):
    x1 = pd.Series(x1).dropna()
    x2 = pd.Series(x2).dropna()

    if len(x1) < 10 or len(x2) < 10:
        return np.nan

    combined = pd.concat([x1, x2])

    if combined.nunique() <= 1:
        return np.nan

    hist_range = (combined.min(), combined.max())

    h1, edges = np.histogram(x1, bins=bins, range=hist_range, density=True)
    h2, _ = np.histogram(x2, bins=bins, range=hist_range, density=True)

    bin_width = edges[1] - edges[0]
    overlap = np.sum(np.minimum(h1, h2)) * bin_width

    return overlap


