"""# Calculate CKD-EPI 2021 eGFR"""

def egfr_ckd_epi_2021(row):
    scr = row.get("serum_creatinine", np.nan)
    age = row.get("age", np.nan)
    sex = row.get("sex", np.nan)

    if pd.isna(scr) or pd.isna(age) or pd.isna(sex) or scr <= 0:
        return np.nan

    # NHANES RIAGENDR: 1 = Male, 2 = Female
    if sex == 2:
        k = 0.7
        alpha = -0.241
        sex_multiplier = 1.012
    else:
        k = 0.9
        alpha = -0.302
        sex_multiplier = 1.0

    ratio = scr / k

    egfr = (
        142
        * (min(ratio, 1) ** alpha)
        * (max(ratio, 1) ** -1.200)
        * (0.9938 ** age)
        * sex_multiplier
    )

    return egfr


df["egfr"] = df.apply(egfr_ckd_epi_2021, axis=1)

